use std::fs::File;
use std::io::Write;
use verryte_terminal::{image_to_grid_with_chroma_key, Color, ResolutionTier};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let assets = [
        ("kael", "kael.png", false),
        ("lyra", "lyra.png", false),
        ("mira", "mira.png", false),
        ("blight-sovereign", "blight-sovereign.png", true),
    ];

    let mut out = File::create("prototype/wuthering-terminal/src/generated_assets.rs")?;
    writeln!(out, "// Generated by bake_assets.rs. Do not edit.\n")?;
    writeln!(
        out,
        "use verryte_terminal::{{Grid, Sprite, Frame, ResolutionTier, VisualAsset, VisualRegistry}};\n"
    )?;

    writeln!(
        out,
        "pub fn register_assets(registry: &mut VisualRegistry) {{"
    )?;

    for (key, filename, is_boss) in assets {
        let path = format!("prototype/wuthering-terminal/assets/{}", filename);
        let img = image::io::Reader::open(&path)?
            .with_guessed_format()?
            .decode()?;

        writeln!(out, "    {{")?;
        writeln!(
            out,
            "        let mut sprite = Sprite::new({:?}, vec![]);",
            key
        )?;

        for tier in ResolutionTier::ALL {
            let (cols, rows) = tier.sprite_size();
            let (w, h) = if is_boss {
                (
                    ((cols as f32 * 1.33) as u32).max(1),
                    ((rows as f32 * 2.0 * 1.33) as u32).max(1),
                )
            } else {
                (cols as u32, rows as u32 * 2)
            };
            let resized = img.resize_exact(w, h, image::imageops::FilterType::Lanczos3);
            let grid = image_to_grid_with_chroma_key(&resized, Color(255, 255, 255), 30);
            let bytes = grid.to_bytes();

            write!(
                out,
                "        sprite = sprite.with_tier(ResolutionTier::{:?}, vec![Frame {{ grid: Grid::from_bytes(&{:?}).unwrap(), duration: 1 }}]);",
                tier, bytes
            )?;
            writeln!(out)?;
        }
        writeln!(
            out,
            "        registry.register({:?}, VisualAsset::Animated(sprite));",
            key
        )?;
        writeln!(out, "    }}")?;
    }

    writeln!(out, "}}")?;

    println!("Baked assets into prototype/wuthering-terminal/src/generated_assets.rs");

    Ok(())
}
